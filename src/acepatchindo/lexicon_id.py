_TOKEN_RE = re.compile(
    r"__WXQ[A-Z]+\d+__|__ROMAN_I__|[A-Za-z]+[0-9]+|[A-Za-z]+(?:'[A-Za-z]+)?|\d+(?:\.\d+)?|[^A-Za-z\d_]+"
)
_WORD_CHECK_RE = re.compile(r"^[A-Za-z]+(?:'[A-Za-z]+)?$")

# Post-order English possessives (__POS_MU__ + NounPhrase -> NounPhrase + milikmu)
_POS_MAP = {
    "KU": "milikku",
    "MU": "milikmu",
    "NYA": "miliknya",
    "KITA": "kita",
    "MEREKA": "mereka",
}
_NON_COPULA_WORD = r"(?:__WXQ[A-Z]+\d+__|__ROMAN_I__|(?!adalah\b|akan\b|dapat\b|tidak\b|telah\b|sudah\b|sedang\b|harus\b|perlu\b|menjadi\b)[A-Za-z0-9_]+(?:['’][A-Za-z0-9_]+)?)"
_POS_SWAP_RE = re.compile(
    r"__POS_(KU|MU|NYA|KITA|MEREKA)__\s+"
    rf"({_NON_COPULA_WORD}(?:\s+{_NON_COPULA_WORD}){{0,2}})"
)
_POS_LEFTOVER_RE = re.compile(r"__POS_(KU|MU|NYA|KITA|MEREKA)__")


