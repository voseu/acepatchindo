def _stem_lookup(word_lower: str) -> str | None:
    """Resolve English inflected word (-ies, -es, -s, -ing, -ed, -ly, -er, -est) to Indonesian."""
    if word_lower in WORD_1:
        return WORD_1[word_lower]

    n = len(word_lower)
    if n <= 3:
        return None

    # Plural / 3rd person -ies -> -y
    if word_lower.endswith("ies") and n > 4:
        base = word_lower[:-3] + "y"
        if base in WORD_1:
            return WORD_1[base]

    # -es -> base or base+e
    if word_lower.endswith("es") and n > 4:
        for cand in (word_lower[:-2], word_lower[:-1]):
            if cand in WORD_1 and cand not in _BLOCKED_SHORT_STEMS:
                return WORD_1[cand]

    # -s -> base (avoid -ss, -us, -is)
    if word_lower.endswith("s") and not word_lower.endswith(("ss", "us", "is")):
        cand = word_lower[:-1]
        if cand in WORD_1 and cand not in _BLOCKED_SHORT_STEMS:
            return WORD_1[cand]

    # -ing -> base, base+e, or undoubled consonant
    if word_lower.endswith("ing") and n > 5:
        stem = word_lower[:-3]
        for cand in (stem, stem + "e"):
            if cand in WORD_1 and cand not in _BLOCKED_SHORT_STEMS:
                return WORD_1[cand]
        if (
            len(stem) >= 3
            and stem[-1] == stem[-2]
            and stem[:-1] in WORD_1
            and stem[:-1] not in _BLOCKED_SHORT_STEMS
        ):
            return WORD_1[stem[:-1]]

    # -ied -> -y
    if word_lower.endswith("ied") and n > 4:
        base = word_lower[:-3] + "y"
        if base in WORD_1:
            return WORD_1[base]

    # -ed -> base, base+e, or undoubled consonant
    if word_lower.endswith("ed") and n > 4:
        stem = word_lower[:-2]
        for cand in (stem, word_lower[:-1]):
            if cand in WORD_1 and cand not in _BLOCKED_SHORT_STEMS:
                return WORD_1[cand]
        if (
            len(stem) >= 3
            and stem[-1] == stem[-2]
            and stem[:-1] in WORD_1
            and stem[:-1] not in _BLOCKED_SHORT_STEMS
        ):
            return WORD_1[stem[:-1]]

    # -ly -> secara + adj (strictly when not blocked)
    if word_lower.endswith("ly") and n > 4:
        stem = word_lower[:-2]
        if stem in WORD_1 and WORD_1[stem] and stem not in _BLOCKED_LY_STEMS:
            return f"secara {WORD_1[stem]}"
        if (
            stem.endswith("i")
            and (stem[:-1] + "y") in WORD_1
            and (stem[:-1] + "y") not in _BLOCKED_LY_STEMS
        ):
            return f"secara {WORD_1[stem[:-1] + 'y']}"

    # -er -> lebih + adj (STRICTLY for gradable adjectives)
    if word_lower.endswith("er") and n > 4:
        stem = word_lower[:-2]
        if stem in _GRADABLE_ADJ_STEMS and stem in WORD_1:
            return f"lebih {WORD_1[stem]}"
        if (
            stem.endswith("i")
            and (stem[:-1] + "y") in _GRADABLE_ADJ_STEMS
            and (stem[:-1] + "y") in WORD_1
        ):
            return f"lebih {WORD_1[stem[:-1] + 'y']}"
        if (
            len(stem) >= 3
            and stem[-1] == stem[-2]
            and stem[:-1] in _GRADABLE_ADJ_STEMS
            and stem[:-1] in WORD_1
        ):
            return f"lebih {WORD_1[stem[:-1]]}"

    # -est -> paling + adj (STRICTLY for gradable adjectives)
    if word_lower.endswith("est") and n > 5:
        stem = word_lower[:-3]
        if stem in _GRADABLE_ADJ_STEMS and stem in WORD_1:
            return f"paling {WORD_1[stem]}"
        if (
            stem.endswith("i")
            and (stem[:-1] + "y") in _GRADABLE_ADJ_STEMS
            and (stem[:-1] + "y") in WORD_1
        ):
            return f"paling {WORD_1[stem[:-1] + 'y']}"
        if (
            len(stem) >= 3
            and stem[-1] == stem[-2]
            and stem[:-1] in _GRADABLE_ADJ_STEMS
            and stem[:-1] in WORD_1
        ):
            return f"paling {WORD_1[stem[:-1]]}"

    return None


def _apply_casing(orig: str, repl: str) -> str:
    if not repl or repl.startswith("__POS_"):
        return repl
    if orig[0].isupper() and not orig.isupper():
        return repl[0].upper() + repl[1:]
    return repl


def translate_segment_en_to_id(segment: str) -> str:
    """Translate an English segment (with __WXQ*__ sentinels already placed) into natural Indonesian."""
    out = segment.replace("’", "'").replace("‘", "'")

    # Roman numeral I protection
    out = re.sub(r"(?:^|(?<=[\n>(]))(\s*)I(?=\s*[.):、])", r"\1__ROMAN_I__", out)
    out = re.sub(r"(?<=\()\s*I\s*(?=\))", "__ROMAN_I__", out)
    out = re.sub(
        r"\b(Stage|Phase|Tier|Part|Chapter|Act|Season|Round|Level|Lv\.?)\s+I\b",
        r"\1 __ROMAN_I__",
        out,
    )

    for pat, repl in CLAUSE_PATTERNS:
        out = pat.sub(repl, out)

    tokens = _TOKEN_RE.findall(out)
    # Build index of word positions for N-gram matching
    n = len(tokens)
    result_tokens: list[str] = []
    i = 0
    while i < n:
        tok = tokens[i]
        if not _WORD_CHECK_RE.match(tok):
            result_tokens.append(tok)
            i += 1
            continue

        w0 = tok.lower()
        # Check 4-gram (tok, space, w1, space, w2, space, w3)
        if (
            i + 6 < n
            and tokens[i + 1] == " "
            and tokens[i + 3] == " "
            and tokens[i + 5] == " "
            and _WORD_CHECK_RE.match(tokens[i + 2])
            and _WORD_CHECK_RE.match(tokens[i + 4])
            and _WORD_CHECK_RE.match(tokens[i + 6])
        ):
            key4 = (w0, tokens[i + 2].lower(), tokens[i + 4].lower(), tokens[i + 6].lower())
            if key4 in PHRASE_4:
                result_tokens.append(_apply_casing(tok, PHRASE_4[key4]))
                i += 7
                continue

        # Check 3-gram
        if (
            i + 4 < n
            and tokens[i + 1] == " "
            and tokens[i + 3] == " "
            and _WORD_CHECK_RE.match(tokens[i + 2])
            and _WORD_CHECK_RE.match(tokens[i + 4])
        ):
            key3 = (w0, tokens[i + 2].lower(), tokens[i + 4].lower())
            if key3 in PHRASE_3:
                result_tokens.append(_apply_casing(tok, PHRASE_3[key3]))
                i += 5
                continue

        # Check 2-gram
        if (
            i + 2 < n
            and tokens[i + 1] == " "
            and _WORD_CHECK_RE.match(tokens[i + 2])
        ):
            key2 = (w0, tokens[i + 2].lower())
            if key2 in PHRASE_2:
                result_tokens.append(_apply_casing(tok, PHRASE_2[key2]))
                i += 3
                continue

        # Check 1-gram + stemmer
        mapped = _stem_lookup(w0)
        if mapped is not None:
            if mapped == "":
                # Skip trailing single space when dropping definite article 'the'
                if i + 1 < n and tokens[i + 1] == " ":
                    i += 2
                else:
                    i += 1
                continue
            result_tokens.append(_apply_casing(tok, mapped))
        else:
            result_tokens.append(tok)
        i += 1

    joined = "".join(result_tokens)

    # Flip [Possessive + Noun Phrase] -> [Noun Phrase + Possessive]
    if "__POS_" in joined:
        joined = _POS_SWAP_RE.sub(
            lambda m: f"{m.group(2)} {_POS_MAP[m.group(1)]}", joined
        )
        joined = _POS_LEFTOVER_RE.sub(lambda m: _POS_MAP[m.group(1)], joined)

    # Clean up redundant spaces
    joined = re.sub(r" {2,}", " ", joined)
    joined = re.sub(r" +([,.;:!?])", r"\1", joined)

    # Post-processing grammar cleanups
    joined = re.sub(
        r"\bke\s+(me[a-z]+|ber[a-z]+|ter[a-z]+|di[a-z]+|memper[a-z]+|meng[a-z]+|meny[a-z]+|men[a-z]+|mem[a-z]+|mel[a-z]+|mer[a-z]+)\b",
        r"untuk \1",
        joined,
    )
    joined = re.sub(r"\bLuban\s+Tidak(?:\.\s*|\s+)(\d+)\b", r"Luban No.\1", joined)
    joined = re.sub(r"\bTidak\.\s*(\d+)\b", r"No.\1", joined)
    joined = joined.replace("[Hebat Dinding]", "[Great Wall]")
    joined = re.sub(r"\bHebat Dinding\b", "Great Wall", joined)
    joined = re.sub(r"\bMechanical Minion sebuah(\d+)\b", r"Mechanical Minion A\1", joined)
    joined = re.sub(r"(?i)\bmementalkan\s+atas\b", "Knock-Up", joined)
    joined = re.sub(r"(?i)\bDamage\s+Atas\b", "Peningkatan Damage", joined)
    joined = re.sub(r"(?i)\bDecay\s+Bawah\b", "Pengurangan Decay", joined)
    joined = re.sub(r"(?i)\bBatas\s+Atas\b", "Peningkatan Batas", joined)
    joined = re.sub(r"(?i)\bpada\s+skill\s+menggunakan\b", "saat menggunakan Skill", joined)
    joined = re.sub(r"(?i)\bpada\s+menggunakan\b", "saat digunakan", joined)
    joined = re.sub(r"\bdasar\s+([A-Z][A-Za-z0-9'&.\- ]{1,25}?)\s+serangan\b", r"Basic Attack \1", joined)
    joined = re.sub(r"\bdasar\s+serangan\b", "Basic Attack", joined)

    # 1. Passive adalah di... / adalah ter... cleanup and redundant copulas
    joined = re.sub(r"\badalah\s+(di[a-z]{3,}\b)", r"\1", joined, flags=re.I)
    joined = re.sub(r"\badalah\s+(ter[a-z]{3,}\b)", r"\1", joined, flags=re.I)
    joined = re.sub(r"\bsebuah\s+(?=\d)", "", joined, flags=re.I)
    joined = re.sub(r"\badalah\s+milikmu\b", "milikmu", joined, flags=re.I)
    joined = re.sub(r"\b(milikku|milikmu|miliknya)\s+adalah\b", r"\1", joined, flags=re.I)
    joined = re.sub(r"(?i)\bTemporary Level\s+atas\b", "Peningkatan Temporary Level", joined)
    joined = re.sub(r"(?i)\bLevel\s+atas\b", "naik Level", joined)

    # 2. Strip unnatural English copulas
    joined = re.sub(
        r"\b(aku|kamu|dia|kami|kita|mereka) adalah (di |ke |dari |pada |lebih |paling |sedang |sudah |telah |akan |bisa |dapat )",
        r"\1 \2",
        joined,
        flags=re.I,
    )
    # 3. Reorder 'sebuah <adj> <noun>' -> '<noun> <adj>'
    joined = re.sub(
        r"\bsebuah (besar|kecil|baru|lama|hebat|indah|kuat|cepat|khusus|langka) ([A-Za-z0-9_]+)\b",
        r"\2 \1",
        joined,
        flags=re.I,
    )
    # 4. Reorder '<verb/prep> ini/itu <noun>' -> '<verb/prep> <noun> ini/itu'
    joined = re.sub(
        r"\b(memakai|memilih|membeli|menggunakan|dalam|dari|untuk|ke) (ini|itu) ([A-Za-z0-9_]+)\b",
        r"\1 \3 \2",
        joined,
        flags=re.I,
    )

    joined = joined.replace("__ROMAN_I__", "I")
    return joined
